const clearFolder = (dir) => {
  if (!fs.existsSync(dir)) return 0;
  let n = 0;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) n += clearFolder(p);
    else { fs.unlinkSync(p); n++; }
  }
  return n;
};

