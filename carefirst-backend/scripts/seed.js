// A small one-page PDF with a few lines of text (receipts, reports, documents)
const pdf = (title, lines) => {
  const esc = (s) => s.replace(/[\\()]/g, c => `\\${c}`);
  const text = [`BT /F1 20 Tf 60 770 Td (${esc(title)}) Tj ET`]
    .concat(lines.map((l, i) => `BT /F1 12 Tf 60 ${730 - i * 22} Td (${esc(l)}) Tj ET`))
    .concat([`BT /F1 9 Tf 60 60 Td (${esc('CareFirst demo document - generated by scripts/seed.js')}) Tj ET`])
    .join('\n');
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>',
    `<< /Length ${Buffer.byteLength(text)} >>\nstream\n${text}\nendstream`,
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
  ];
  let out = '%PDF-1.4\n';
  const offsets = objects.map((obj, i) => { const at = Buffer.byteLength(out); out += `${i + 1} 0 obj\n${obj}\nendobj\n`; return at; });
  const xref = Buffer.byteLength(out);
  out += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n${offsets.map(o => `${String(o).padStart(10, '0')} 00000 n \n`).join('')}`;
  out += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return out;
};

let fileCount = 0;
const saveFile = (folder, title, lines) => {
  fs.mkdirSync(path.join(UPLOADS, folder), { recursive: true });
  const name = `seed-${++fileCount}-${title.toLowerCase().replace(/[^a-z0-9]+/g, '-').slice(0, 40)}.pdf`;
  fs.writeFileSync(path.join(UPLOADS, folder, name), pdf(title, lines));
  return fileUrl(folder, name);
};
