// Next date (from `fromOffset` days ahead) whose weekday is in `days`
const nextDateOn = (days, fromOffset = 0) => {
  for (let i = fromOffset; i < fromOffset + 14; i++) {
    const d = addDays(today, i);
    if (days.includes(weekdayOf(d))) return d;
  }
  return addDays(today, fromOffset);
};

// An appointment at a real instant (date/time in PKT)
const appointment = async ({ patient, doctor, startsAt, status = 'confirmed', fee, duration, ...rest }) => {
  const pkt = new Date(startsAt.getTime() + 5 * 3600 * 1000);
  return Appointment.create({
    patient: patient._id, doctor: doctor._id,
    date: pkt.toISOString().slice(0, 10), time: pkt.toISOString().slice(11, 16),
    startsAt, durationMinutes: duration, fee, status, ...rest,
  });
};

// An installment plan exactly as the app would create it, in the requested state
const makePlan = async ({ patientKey, labKey, testName, guarantor, state, approvedDaysAgo = 1, activatedDaysAgo }) => {
  const patient = users[patientKey];
  const profile = await PatientProfile.findOne({ user: patient._id });
  const labProfile = await LabProfile.findOne({ user: users[labKey]._id });
  const test = labProfile.tests.find(t => t.name === testName);
  const total = Math.round(test.price);
  const { downPayment, installments } = planAmounts(total, test.installmentCount);

  const input = {
    patient, patientCnic: profile.cnic, patientAddress: profile.address, guarantor, labName: labProfile.labName, testName: test.name,
    totalAmount: total, downPayment, installments, tenureDays: test.installmentTenureDays,
    serviceFee: SERVICE_FEE, graceDays: GRACE_DAYS,
  };
  const wallet = new Wallet({
    patient: patient._id, lab: users[labKey]._id, labTest: test._id, testName: test.name,
    totalAmount: total, installmentCount: installments.length, installmentTenureDays: test.installmentTenureDays,
    downPayment: { amount: downPayment }, serviceFee: { amount: SERVICE_FEE },
    patientCnic: profile.cnic, patientAddress: profile.address, guarantor,
    cnicPictures: {
      patientFront:   await cnicCard(patient.name, profile.cnic, 'front'),
      patientBack:    await cnicCard(patient.name, profile.cnic, 'back', profile.address),
      guarantorFront: await cnicCard(guarantor.name, guarantor.cnic, 'front'),
      guarantorBack:  await cnicCard(guarantor.name, guarantor.cnic, 'back', guarantor.address),
    },
    agreement: { text: generateInstallmentAgreement(input), textUrdu: generateInstallmentAgreementUrdu(input), acceptedAt: daysAgo(approvedDaysAgo + 1) },
    status: 'pending_approval',
  });

  if (state !== 'pending_approval') {
    wallet.status = 'awaiting_fee';
    wallet.planApprovedAt = daysAgo(approvedDaysAgo);
    wallet.planApprovedBy = users.admin._id;
  }
  if (activatedDaysAgo !== undefined) {
    const activatedAt = daysAgo(activatedDaysAgo);
    wallet.serviceFee.receiptUrl = receipt(patient.name, 'CareFirst service fee', SERVICE_FEE, 'CareFirst');
    wallet.serviceFee.receiptUploadedAt = activatedAt;
    wallet.serviceFee.adminVerified = true;
    wallet.serviceFee.adminVerifiedAt = activatedAt;
    wallet.serviceFee.adminVerifiedBy = users.admin._id;
    wallet.installments = buildSchedule(installments, test.installmentTenureDays, activatedAt);
    wallet.activatedAt = activatedAt;
    wallet.status = 'active';
  }
  return { wallet, labProfile, test };
};

